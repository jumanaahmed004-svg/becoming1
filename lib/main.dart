import 'package:firebase_auth/firebase_auth.dart';
import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/material.dart';

import 'firebase_options.dart'; // generated by `flutterfire configure`
import 'screens/dashboard_page.dart';
import 'screens/login_page.dart';
import 'theme.dart';
import 'widgets/aurora_background.dart';
import 'widgets/brand_logo.dart';

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  runApp(const BecomingApp());
}

class BecomingApp extends StatelessWidget {
  const BecomingApp({super.key});

  @override
  Widget build(BuildContext context) => MaterialApp(
        title: 'BECOMING',
        debugShowCheckedModeBanner: false,
        theme: buildTheme(),
        home: const AuthGate(),
      );
}

/// Listens to Firebase Auth. Signed out -> Login. Signed in -> Dashboard.
/// The screens are swapped (not pushed), so the Back button can never return
/// to Login after signing in, or to the Dashboard after logging out.
class AuthGate extends StatelessWidget {
  const AuthGate({super.key});

  @override
  Widget build(BuildContext context) => StreamBuilder<User?>(
        stream: FirebaseAuth.instance.authStateChanges(),
        builder: (context, snap) {
          if (snap.connectionState == ConnectionState.waiting) return const SplashView();
          final user = snap.data;
          return AnimatedSwitcher(
            duration: const Duration(milliseconds: 500),
            child: user == null
                ? const LoginPage(key: ValueKey('login'))
                : DashboardPage(key: ValueKey(user.uid)),
          );
        },
      );
}

class SplashView extends StatefulWidget {
  const SplashView({super.key});
  @override
  State<SplashView> createState() => _SplashViewState();
}

class _SplashViewState extends State<SplashView> with SingleTickerProviderStateMixin {
  late final AnimationController _c =
      AnimationController(vsync: this, duration: const Duration(milliseconds: 1100))
        ..repeat(reverse: true);

  @override
  void dispose() {
    _c.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) => Scaffold(
        body: AuroraBackground(
          child: Center(
            child: ScaleTransition(
              scale: Tween<double>(begin: 0.9, end: 1.05)
                  .animate(CurvedAnimation(parent: _c, curve: Curves.easeInOut)),
              child: const BrandMark(size: 84),
            ),
          ),
        ),
      );
}
